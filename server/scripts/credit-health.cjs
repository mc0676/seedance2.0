const D=require('better-sqlite3'),db=new D('/app/server/data/seedance.db');
console.log('=== 积分系统健康检查 ===');
const tu=db.prepare('SELECT SUM(credits) total, COUNT(*) users FROM users').get();
console.log('总积分:', tu.total||0, 'cr  用户:', tu.users);
const lk=db.prepare("SELECT SUM(locked_credits) locked, COUNT(*) count FROM credit_locks WHERE status='locked'").get();
console.log('锁定中:', lk.locked||0, 'cr', lk.count||0, '条');
const neg=db.prepare('SELECT COUNT(*) c FROM users WHERE credits<0').get();
console.log('负余额:', neg.c, '用户');
const unlim=db.prepare('SELECT COUNT(*) c FROM users WHERE unlimited_credits=1').get();
console.log('无限额度:', unlim.c, '用户');
const codes=db.prepare('SELECT SUM(credits_value*max_uses) issued, COUNT(*) count FROM activation_codes').get();
console.log('激活码发分:', codes.issued||0, 'cr', codes.count, '个');
const adm=db.prepare('SELECT SUM(credits_amount) issued, COUNT(*) count FROM credit_distribution_logs').get();
console.log('管理员发分:', adm.issued||0, 'cr', adm.count, '条');
const ul=db.prepare('SELECT SUM(credits_cost) spent, COUNT(*) calls FROM usage_logs').get();
console.log('总消耗:', ul.spent||0, 'cr', ul.calls, '次');
const waste=db.prepare("SELECT SUM(credits_cost) wasted FROM usage_logs WHERE status='failed'").get();
console.log('失败浪费:', waste.wasted||0, 'cr');
const zombie=db.prepare("SELECT COUNT(*) c FROM credit_locks WHERE status='locked' AND created_at<datetime('now','-1 hour')").get();
console.log('超1h僵尸锁:', zombie.c, '条');
const top=db.prepare("SELECT u.email,u.credits,u.created_at FROM users u ORDER BY u.credits DESC LIMIT 10").all();
console.log('\n=== 积分TOP10 ===');
top.forEach(r=>console.log(r.email, r.credits+'cr', r.created_at));
db.close();
